#!/usr/bin/env python3
"""Scaffold a coordination hub, check it, or print repo state. Stdlib only."""
import argparse, json, subprocess, sys
from pathlib import Path

TPL = Path(__file__).resolve().parent.parent / "assets" / "templates"
SKIP = {"scripts", "assets", "node_modules"}


def read(name):
    return (TPL / name).read_text()


def domains_in(hub):
    return sorted(d.name for d in hub.iterdir()
                  if d.is_dir() and not d.name.startswith(("_", ".")) and d.name not in SKIP)


def render_map(domains):
    lines = ["# Coordination map", "", "Generated by scaffold_hub.py. Do not edit by hand.", "", "## Domains", ""]
    lines += [f"- `{d}/`: see `{d}/AGENTS.md`" for d in domains] or ["- (none yet)"]
    return "\n".join(lines) + "\n"


def plan(hub, domains):
    files = {
        "AGENTS.md": read("hub-AGENTS.md"),
        "CONTEXT.md": "# Glossary\n\nTerm: meaning. Where used.\n",
        "repo-registry.md": read("repo-registry.md"),
        "_ADR/README.md": "# Decisions\n\nNumbered `NNNN-title.md`. Template: skill `coordination-hub`, `assets/templates/adr.md`.\n",
        ".remember/now.md": read("now.md"),
        "domains.json": json.dumps({"domains": [{"name": d, "path": f"{d}/"} for d in domains]}, indent=2) + "\n",
        "COORDINATION-MAP.md": render_map(domains),
    }
    for d in domains:
        files[f"{d}/AGENTS.md"] = read("domain-AGENTS.md").replace("<Domain>", d)
        files[f"{d}/_TASK-LOG/.gitkeep"] = ""
    return {hub / k: v for k, v in files.items()}


def scaffold(hub, domains, dry):
    for path, text in plan(hub, domains).items():
        if path.exists():
            print(f"skip (exists): {path}")
            continue
        print(f"{'would create' if dry else 'create'}: {path}")
        if not dry:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


def check(hub):
    problems = []
    domains = domains_in(hub)
    mp = hub / "COORDINATION-MAP.md"
    mtext = mp.read_text() if mp.exists() else ""
    if not mp.exists():
        problems.append("missing COORDINATION-MAP.md")
    for d in domains:
        if not (hub / d / "AGENTS.md").is_file():
            problems.append(f"{d}: missing AGENTS.md")
        if not (hub / d / "_TASK-LOG").is_dir():
            problems.append(f"{d}: missing _TASK-LOG/")
        if mp.exists() and f"`{d}/`" not in mtext:
            problems.append(f"{d}: not listed in COORDINATION-MAP.md")
    for name in ("AGENTS.md", "repo-registry.md", ".remember/now.md"):
        if not (hub / name).exists():
            problems.append(f"missing {name}")
    for p in problems:
        print("PROBLEM:", p)
    print(f"checked {len(domains)} domain(s): {'OK' if not problems else str(len(problems)) + ' problem(s)'}")
    return 1 if problems else 0


def git(path, *args):
    r = subprocess.run(["git", "-C", str(path), *args], capture_output=True, text=True)
    return r.returncode, r.stdout.strip()


def status(hub):
    reg = hub / "repo-registry.md"
    if not reg.exists():
        print("no repo-registry.md")
        return 1
    for line in reg.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0] in ("Name", "") or set(cells[0]) <= {"-"}:
            continue
        name, path = cells[0], Path(cells[1]).expanduser()
        if not (path / ".git").exists():
            print(f"{name}: path missing or not a git repo ({path})")
            continue
        git(path, "fetch", "--quiet")
        dirty = len(git(path, "status", "--porcelain")[1].splitlines())
        rc1, ahead = git(path, "rev-list", "--count", "@{u}..HEAD")
        rc2, behind = git(path, "rev-list", "--count", "HEAD..@{u}")
        sync = f"ahead {ahead}, behind {behind}" if rc1 == 0 and rc2 == 0 else "no upstream"
        extra = len(git(path, "worktree", "list")[1].splitlines()) - 1
        flags = "; DIVERGED, ask the user" if sync != "no upstream" and ahead != "0" and behind != "0" else ""
        print(f"{name}: {dirty} changed file(s); {sync}; {extra} extra worktree(s){flags}")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("hub", help="hub directory")
    ap.add_argument("--domains", default="writing,teaching,apps,admin", help="comma-separated domain names")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true", help="verify domains, map and core files")
    ap.add_argument("--status", action="store_true", help="print git state of each repo in repo-registry.md")
    a = ap.parse_args()
    hub = Path(a.hub).expanduser()
    if a.check:
        return check(hub)
    if a.status:
        return status(hub)
    domains = [d.strip() for d in a.domains.split(",") if d.strip()]
    scaffold(hub, domains, a.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
