#!/usr/bin/env node
// Build video-player.js: the companion page's video player as one dependency-free script for any web page
// (explainers, handouts, gallery pages). Reuses companion-player.mjs and the companion DOM helpers verbatim,
// like build-journey.mjs, so fixes to the player reach every page on the next build.
//
// Usage: node embed-player.mjs [out=video-player.js]
//
// Page markup (works with JavaScript off: the plain <video controls> is the fallback):
//   <figure data-video-player data-chapters='[{"start":0,"title":"Intro"},{"start":12,"title":"Part 1"}]'
//           data-duration="64" [data-captions="media/captions.vtt"] [data-muted]>
//     <video controls playsinline preload="metadata" poster="media/poster.jpg" src="media/video.mp4"></video>
//     <figcaption>…</figcaption>
//   </figure>
//   <script src="video-player.js" defer></script>
// Colours: set --vp-accent, --vp-surface, --vp-ink, --vp-line, --vp-soft on the page (light and dark) to match it.
// Keyboard shortcuts (Space/K, J/L, arrows, F, M, C, ?) act only while the player has focus or was last clicked,
// so they never hijack page scrolling.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { playerCSS, playerScript } from './companion-player.mjs';

const dir = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(process.argv[2] || 'video-player.js');
const companion = readFileSync(path.join(dir, 'companion.mjs'), 'utf8');
const helpers = companion.slice(companion.indexOf('var ICONS='), companion.indexOf('var PK='));
if (!helpers.includes('function h(') || !helpers.includes('function sget(')) throw Error('companion helper slice moved: update embed-player.mjs');

const script = playerScript
  .replaceAll("'video-speeds'", "'vp-speeds-'+index")
  .replaceAll("'video-shortcuts'", "'vp-shortcuts-'+index")
  .replaceAll("'video-more'", "'vp-more-'+index");

// Defaults sit on .video-player, not on the figure: a page may set --vp-ink:var(--ink) on the figure, and
// redefining --ink on that same element would make a cycle that invalidates both.
const css = `[data-video-player]{margin:0}
[data-video-player] .video-player{--r:12px;--shadow-lg:0 10px 30px rgba(0,0,0,.12);--green:var(--vp-accent,#287454);--blue:var(--vp-accent,#336b91);--surface:var(--vp-surface,#fff);--ink:var(--vp-ink,#1e2925);--line:var(--vp-line,#d9ded6);--soft:var(--vp-soft,#eef0ea);color:var(--ink)}
[data-video-player] .video-player video{display:block;width:100%;height:auto;aspect-ratio:16/9;background:#000;border-radius:var(--r) var(--r) 0 0}
[data-video-player] .vp-live{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0)}
@media(prefers-reduced-motion:reduce){[data-video-player] *{transition:none!important}}
` + playerCSS;

const js = `/* video-player.js v1: generated by animated-talk-video/scripts/embed-player.mjs from companion-player.mjs. Do not edit; rebuild. */
(function(){'use strict';var NS='http://www.w3.org/2000/svg';
${helpers}
var style=document.createElement('style');style.textContent=${JSON.stringify(css)};document.head.appendChild(style);
function mount(fig,index){
 var old=fig.querySelector('video');if(!old||fig.dataset.vpMounted)return;fig.dataset.vpMounted='1';
 var src=old.getAttribute('src')||(old.querySelector('source')||{getAttribute:function(){return ''}}).getAttribute('src');
 var chapters=[];try{chapters=JSON.parse(fig.dataset.chapters||'[]')}catch(e){}
 if(!chapters.length)chapters=[{start:0,title:fig.dataset.title||''}];
 var D={duration:Number(fig.dataset.duration)||chapters[chapters.length-1].start||0,captions:fig.dataset.captions||null,burnedCaptions:!fig.dataset.captions};
 var video=h('video',{playsinline:true,preload:'metadata',poster:old.getAttribute('poster'),'aria-label':old.getAttribute('aria-label')},h('source',{src:src,type:'video/mp4'}));
 if(D.captions)video.appendChild(h('track',{kind:'captions',src:D.captions,srclang:'en',label:'English'}));
 if(fig.hasAttribute('data-muted')||old.muted)video.muted=true;
 var live=h('span',{class:'vp-live',role:'status','aria-live':'polite'});function announce(t){live.textContent='';setTimeout(function(){live.textContent=t},30)}
 function seek(t,play){if(!isFinite(t))return;var go=function(){video.currentTime=t;if(play){var p=video.play();if(p&&p.catch)p.catch(function(){})}};if(video.readyState>0)go();else video.addEventListener('loadedmetadata',go,{once:true})}
 var active=false,el={get hidden(){return !(active||player.contains(document.activeElement)||document.fullscreenElement===player)}};
${script}
 video.addEventListener('loadedmetadata',function(){if(!D.duration)D.duration=video.duration});
 document.addEventListener('pointerdown',function(e){active=player.contains(e.target)},true);
 player.appendChild(live);old.replaceWith(player);
}
function init(){Array.prototype.forEach.call(document.querySelectorAll('[data-video-player]'),mount)}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
})();
`;
writeFileSync(out, js);
console.log('wrote', out, Math.round(js.length / 1024) + ' KB');
